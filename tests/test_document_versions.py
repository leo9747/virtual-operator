"""Edited copies of indexed Markdown documents: versioned, conflict-checked, never in place."""
import hashlib
import sqlite3
import threading

from tests.test_saved_review import auth, review_dir  # noqa: F401  (fixture re-export)


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


ALPHA = "# Synthetic Alpha\n\nThis is local QA content; nothing external happened.\n"


def save(client, text, base_version, original_sha256=None, name="alpha.md"):
    return client.post(
        f"/api/saved-drafts/{name}/versions",
        headers=auth(),
        json={"text": text, "base_version": base_version,
              "original_sha256": original_sha256 or digest(ALPHA)},
    )


def test_listing_reports_modified_time_and_markdown_digest(client, review_dir):
    items = client.get("/api/saved-drafts", headers=auth()).json()["items"]
    assert all(item["modifiedAt"].endswith("+00:00") for item in items)
    content = client.get("/api/saved-drafts/alpha.md/content", headers=auth()).json()
    assert content["sha256"] == digest(ALPHA)


def test_versions_start_empty_and_require_the_access_key(client, review_dir):
    assert client.get("/api/saved-drafts/alpha.md/versions").status_code == 401
    assert client.post("/api/saved-drafts/alpha.md/versions", json={}).status_code == 401
    response = client.get("/api/saved-drafts/alpha.md/versions", headers=auth())
    assert response.status_code == 200, response.text
    assert response.json() == {
        "fileId": "alpha.md", "originalSha256": digest(ALPHA), "versions": [],
        "latest": None, "originalChanged": False, "originalWritten": False,
    }


def test_saving_creates_versions_without_touching_the_original(client, review_dir):
    original_path = review_dir / "alpha.md"
    before = (original_path.read_bytes(), original_path.stat().st_mtime_ns, original_path.stat().st_mode)
    first = save(client, "# Synthetic Alpha\n\nEdited once.\n", 0)
    assert first.status_code == 201, first.text
    assert first.json()["version"] == 1
    assert first.json()["sha256"] == digest("# Synthetic Alpha\n\nEdited once.\n")
    assert "text" not in first.json()
    second = save(client, "# Synthetic Alpha\n\nEdited twice. ünïcode ✓\n", 1)
    assert second.status_code == 201, second.text
    assert second.json()["version"] == 2

    state = client.get("/api/saved-drafts/alpha.md/versions", headers=auth()).json()
    assert [entry["version"] for entry in state["versions"]] == [1, 2]
    assert state["latest"]["text"] == "# Synthetic Alpha\n\nEdited twice. ünïcode ✓\n"
    assert state["latest"]["bytes"] == len(state["latest"]["text"].encode("utf-8"))
    assert state["originalChanged"] is False
    after = (original_path.read_bytes(), original_path.stat().st_mtime_ns, original_path.stat().st_mode)
    assert after == before
    assert sorted(path.name for path in review_dir.iterdir()) == sorted([
        ".work", "INDEX.md", "alpha.md", "inventory.csv", "payments.xlsx",
        "placeholder.md", "tone-analysis.md", "tone-prompt.md",
    ])
    # The original content endpoint still serves the untouched original.
    assert client.get("/api/saved-drafts/alpha.md/content", headers=auth()).json()["text"] == ALPHA


def test_stale_base_version_is_rejected(client, review_dir):
    assert save(client, "one", 0).status_code == 201
    stale = save(client, "two from another tab", 0)
    assert stale.status_code == 409
    assert stale.json()["detail"]["code"] == "version_conflict"
    assert stale.json()["detail"]["latestVersion"] == 1
    assert [v["version"] for v in client.get(
        "/api/saved-drafts/alpha.md/versions", headers=auth()).json()["versions"]] == [1]


def test_concurrent_saves_from_the_same_base_produce_exactly_one_version(client, review_dir):
    results = []
    barrier = threading.Barrier(6)

    def worker(index):
        barrier.wait()
        results.append(save(client, f"text {index}", 0).status_code)

    threads = [threading.Thread(target=worker, args=(index,)) for index in range(6)]
    for thread in threads:
        thread.start()
    for thread in threads:
        thread.join()
    assert sorted(results) == [201, 409, 409, 409, 409, 409]


def test_changed_original_is_detected_on_save_and_on_read(client, review_dir):
    assert save(client, "edited", 0).status_code == 201
    path = review_dir / "alpha.md"
    path.write_text("# Regenerated by the agent\n", encoding="utf-8")
    path.chmod(0o600)
    state = client.get("/api/saved-drafts/alpha.md/versions", headers=auth()).json()
    assert state["originalChanged"] is True
    assert state["originalSha256"] == digest("# Regenerated by the agent\n")

    stale = save(client, "edited again", 1, original_sha256=digest(ALPHA))
    assert stale.status_code == 409
    assert stale.json()["detail"]["code"] == "original_changed"
    assert stale.json()["detail"]["originalSha256"] == digest("# Regenerated by the agent\n")
    accepted = save(client, "edited again", 1, original_sha256=digest("# Regenerated by the agent\n"))
    assert accepted.status_code == 201
    assert client.get("/api/saved-drafts/alpha.md/versions", headers=auth()).json()["originalChanged"] is False


def test_only_indexed_markdown_can_be_edited(client, review_dir):
    assert save(client, "x", 0, name="inventory.csv").status_code == 409
    assert save(client, "x", 0, name="payments.xlsx").status_code == 409
    assert save(client, "x", 0, name="INDEX.md").status_code == 404
    assert save(client, "x", 0, name="unlisted.md").status_code == 404
    assert client.get("/api/saved-drafts/..%2Falpha.md/versions", headers=auth()).status_code == 404
    assert client.get("/api/saved-drafts/inventory.csv/versions", headers=auth()).status_code == 409


def test_payload_validation(client, review_dir):
    assert save(client, "x", -1).status_code == 422
    assert save(client, "x", 0, original_sha256="not-a-digest").status_code == 422
    assert save(client, "contains \x00 nul", 0).status_code == 422
    too_big = "é" * 1_000_001  # 2,000,002 UTF-8 bytes, under the character limit
    assert save(client, too_big, 0).status_code == 413
    oversized = client.post(
        "/api/saved-drafts/alpha.md/versions", headers={**auth(), "Content-Type": "application/json"},
        content=b"{" + b" " * 5_000_001 + b"}",
    )
    assert oversized.status_code == 413


def test_edited_version_download_is_exact_and_authenticated(client, review_dir):
    text = "# Synthetic Alpha\n\nDownload me — exactly.\n"
    assert save(client, text, 0).status_code == 201
    assert client.get("/api/saved-drafts/alpha.md/versions/1/download").status_code == 401
    download = client.get("/api/saved-drafts/alpha.md/versions/1/download", headers=auth())
    assert download.status_code == 200
    assert download.content == text.encode("utf-8")
    assert download.headers["content-type"].startswith("text/markdown")
    assert download.headers["content-disposition"] == (
        "attachment; filename=\"alpha.edited-v1.md\"; filename*=utf-8''alpha.edited-v1.md"
    )
    assert download.headers["x-content-type-options"] == "nosniff"
    assert client.get("/api/saved-drafts/alpha.md/versions/9/download", headers=auth()).status_code == 404


def test_versions_live_in_the_private_database(client, review_dir, tmp_path):
    assert save(client, "private edit", 0).status_code == 201
    database = tmp_path / "data" / "operator.db"
    assert database.stat().st_mode & 0o777 == 0o600
    with sqlite3.connect(database) as db:
        rows = db.execute("SELECT file_id, version, text FROM document_versions").fetchall()
    assert rows == [("alpha.md", 1, "private edit")]
